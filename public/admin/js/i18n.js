// Export globally to window
window.i18n = i18n;
window.currentLang = localStorage.getItem('abentra_admin_lang') || 'tr';

function t(key, fallback = '') {
  const lang = window.currentLang || 'tr';
  if (i18n[lang] && i18n[lang][key]) return i18n[lang][key];
  if (i18n['en'] && i18n['en'][key]) return i18n['en'][key];
  if (i18n['tr'] && i18n['tr'][key]) return i18n['tr'][key];
  return fallback || key;
}

window.t = t;

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { i18n, t };
}
